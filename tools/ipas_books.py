def page_no(p):
    return int(p.split("-")[1])


def units(s):
    """書的每一小節：[{u, t, sec, sect, p, n}]，n 是估的頁數（下一小節起始頁減這一小節，最少 0.5 頁）。"""
    b = BOOKS[s]
    flat = [(sec, sname, u, t, p) for sec, sname, us in b["sections"] for u, t, p, _ in us]
    out = []
    for i, (sec, sname, u, t, p) in enumerate(flat):
        ch = sec.split(".")[0]
        nxt = flat[i + 1][4] if i + 1 < len(flat) and flat[i + 1][0].split(".")[0] == ch else "%s-%d" % (ch, b["ends"][ch])
        out.append({"u": u, "t": t, "sec": sec, "sect": sname, "p": p, "n": max(0.5, page_no(nxt) - page_no(p))})
    return out


def _rx(words):
    parts = []
    for w in words.split("|"):
        if not w:
            continue
        parts.append(r"(?<![A-Za-z])" + w + r"(?![A-Za-z])" if re.fullmatch(r"[A-Za-z]{2,5}", w) else w)
    return re.compile("|".join(parts), re.I)


def _title_words(t):
    ws = [w for w in re.split(r"[、與及和（）()\s,/─:]+", t) if len(w) >= 2 and not re.fullmatch(r"[\d.:]+|ISO|IEC|BS|L\d|介紹|概說|概述|基本|觀念|之|定義|使用情境|進階問題", w)]
    return "|".join(re.escape(w) for w in ws)


MATCH = {}
for _s, _b in BOOKS.items():
    MATCH[_s] = [(u, sec, _rx("|".join(x for x in (_title_words(t), kw) if x))) for sec, _, us in _b["sections"] for u, t, _, kw in us]


def match(s, q, hint_sec=None):
    """這一題最相關的小節；題目的分數加倍，跟 hint_sec（關鍵字判斷的節）同一節的加一點。回傳 (小節, 分數)。"""
    best, bs = None, 0
    for u, sec, rx in MATCH[s]:
        v = 2 * len(rx.findall(q["q"])) + len(rx.findall(" ".join(q["o"])))
        if v and hint_sec and sec == hint_sec:
            v += 1.5
        if v > bs:
            best, bs = u, v
    return best, bs
